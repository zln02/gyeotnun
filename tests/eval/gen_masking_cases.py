def build() -> dict:
    cases = []
    for cid, text, spans, non_pii in CASES:
        # --- 안전 검증 1: 스팬 값은 반드시 본문에 원문 그대로 있어야 한다
        for typ, val in spans:
            if val not in text:
                raise SystemExit(f"[{cid}] pii_span 값이 본문에 없다: {typ}={val!r}")
        for tok in non_pii:
            if tok not in text:
                raise SystemExit(f"[{cid}] non_pii 토큰이 본문에 없다: {tok!r}")
        # --- 안전 검증 2: 주민번호는 체크섬이 반드시 틀려야 한다
        for typ, val in spans:
            if typ != "rrn":
                continue
            digits = re.sub(r"[^0-9]", "", val)
            if len(digits) == 13 and rrn_checksum_ok(digits):
                raise SystemExit(f"[{cid}] 실제 발급 가능한 주민번호다. 교체할 것: {val!r}")
        # --- 안전 검증 3: 금지 성명
        for bad in FORBIDDEN_NAMES:
            if bad in text:
                raise SystemExit(f"[{cid}] 금지된 성명 포함: {bad}")

        cases.append({
            "id": cid,
            "text": text,
            "pii_spans": [{"type": t, "value": v} for t, v in spans],
            "non_pii": non_pii,
        })
    return {
        "note": "합성 PII 평가 세트. 실제 개인정보는 한 건도 포함되지 않는다. "
                "주민등록번호는 전부 검증식(체크섬)을 고의로 틀린 값이라 발급될 수 없다. "
                "휴대전화 중간 그룹은 원칙적으로 미할당 대역(0 시작)을 쓰되, "
                "지시서에 명시된 함정 예시(010-1234-5678 계열)만 관용 예시값을 따랐다. "
                "계좌번호는 실제 은행 자릿수 규칙을 따르지 않는 합성값이다. "
                "★ 한국 성명은 조합 수가 적어 실존 인물과의 우연한 일치를 "
                "완전히 배제할 수는 없다(리포트 §한계 참고).",
        "schema": {
            "id": "케이스 ID",
            "text": "마스킹 파이프라인 입력 문장",
            "pii_spans": "마스킹되어야 하는 값 [{type, value}]. type = "
                         "name|phone|account|rrn|address",
            "non_pii": "마스킹되면 안 되는 토큰(과잉 마스킹 측정용). 지시서 스키마의 확장 필드다.",
        },
        "counts": {},
        "cases": cases,
    }


def main() -> None:
    data = build()
    counts: dict[str, int] = {}
    for c in data["cases"]:
        for s in c["pii_spans"]:
            counts[s["type"]] = counts.get(s["type"], 0) + 1
    data["counts"] = {
        "cases": len(data["cases"]),
        "pii_fields_total": sum(counts.values()),
        "by_type": dict(sorted(counts.items())),
        "non_pii_tokens": sum(len(c["non_pii"]) for c in data["cases"]),
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"저장: {OUT}")
    print(f"케이스 {data['counts']['cases']}건 / PII 필드 {data['counts']['pii_fields_total']}개")
    for k, v in data["counts"]["by_type"].items():
        print(f"  {k:<9} {v}")
    print(f"  (비-PII 토큰 {data['counts']['non_pii_tokens']}개)")

    # 지시서 최소 조건 확인
    problems = []
    if data["counts"]["pii_fields_total"] < 150:
        problems.append(f"총 필드 {data['counts']['pii_fields_total']} < 150")
    for t in ("name", "phone", "account", "rrn", "address"):
        n = data["counts"]["by_type"].get(t, 0)
        if n < 20:
            problems.append(f"{t} {n} < 20")
    print("\n최소 조건:", "충족" if not problems else "미달 → " + ", ".join(problems))


if __name__ == "__main__":
    main()
