    HOLD_OUT.parent.mkdir(parents=True, exist_ok=True)
    with HOLD_OUT.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        w.writerows(hold_rows)

    import collections
    print(f"평가세트 : {EVAL_OUT.relative_to(REPO)}  {len(all_rows)}건")
