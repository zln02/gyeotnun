# ---------------------------------------------------------------- URL 조회
def load_index() -> dict[str, dict]:
    if not RECORDS.exists():
        sys.exit(f"[중단] 코퍼스 원본이 없다: {RECORDS}\n"
                 "  이 파일은 gitignore 대상(데이터팀 별도 전달)이라 클론 환경에는 없다.")
    idx: dict[str, dict] = {}
    for line in RECORDS.open(encoding="utf-8"):
        r = json.loads(line)
        idx.setdefault(r.get("title", ""), r)
    return idx


IDX = load_index()
_MISSING: list[str] = []


def url_of(title: str) -> str:
    """제목으로 실제 출처 URL 을 찾는다. 못 찾으면 기록해 두고 끝에서 죽는다."""
    r = IDX.get(title)
    if r is None:
        _MISSING.append(title)
        return ""
    return r.get("source_url") or ""


def agency_of(title: str) -> str:
    r = IDX.get(title)
    return (r or {}).get("source_agency", "")


_NO_RISK: list[str] = []
