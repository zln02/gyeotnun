CATEGORY_LABEL: Dict[str, str] = {k: d for k, _, _, d in _CATEGORIES}


def _has(text: str, words: List[str]) -> bool:
    return any(w in text for w in words)


def detect_categories(text: str) -> Set[str]:
    """글이 '요구하는 행위'를 카테고리 집합으로 돌려준다.

    대상 명사와 요구 동작이 같은 문장 안에 함께 있어야 성립한다.
    문장 단위로 보는 이유: 서로 다른 문장에 흩어져 있는 명사와 동사를
    묶으면 '계좌로 입금되며' + 다른 문장의 '방문해'가 자금이체로 잡힌다.
    """
    t = (text or "").lower()
    if not t:
        return set()

    out: Set[str] = set()
    for sent in re.split(r"[.!?\n·]", t):
        s = sent.strip()
        if not s:
            continue
        # 수동·수령 표현이 있는 절은 '요구'로 보지 않는다
        passive = bool(_PASSIVE.search(s))
        for key, nouns, verbs, _label in _CATEGORIES:
            if not _has(s, nouns):
                continue
            if not _has(s, verbs):
                continue
            # 자금이체·선입금은 수동형이면 정상 수령 안내다 - 제외한다.
            # (다른 카테고리는 수동형이어도 요구인 경우가 있어 그대로 둔다:
            #  예 "앱이 설치되어야 합니다"도 결국 설치를 시킨다.)
            if passive and key in ("fund_transfer", "prepay"):
                continue
            out.add(key)
    return out


def describe_categories(text: str) -> Set[str]:
    """사기 사례 '설명문'이 다루는 수법 카테고리(주제 단위).

    ★ detect_categories() 와 판정 강도가 다르다. 의도적인 비대칭이다.

      사용자 입력은 사기 문자 **원문**이라 "안전계좌로 보내세요"처럼 명령형
      동작이 그대로 들어 있다. 그래서 (명사 ∧ 동작)을 요구해야 정상 안내문
      ("계좌로 입금되며")과 갈린다 - 여기서 느슨해지면 오판이 난다.

      반면 SCAM_CASES 는 사람이 쓴 **서술형 요약**이다("...환급 절차 신청을
      유도한 피싱 이메일"). 원문의 명령형 동사가 남아 있지 않은 경우가 많아,
      입력과 똑같이 (명사 ∧ 동작)을 요구하면 정상 사례까지 대조 대상에서
      빠진다. 실측: S02(안전계좌 송금 요구)가 C07 과 매칭되지 않았다.

      따라서 "이 글이 무엇을 요구하는가"(입력)는 엄격하게, "이 사례가 무슨
      수법에 관한 것인가"(사례)는 주제 수준으로 본다.
    """
    t = (text or "").lower()
    if not t:
        return set()
    return {key for key, nouns, _verbs, _label in _CATEGORIES if _has(t, nouns)}


def shared_categories(user_text: str, case_text: str) -> Set[str]:
    """사용자 입력이 '요구하는 행위'와 사례가 '다루는 수법'의 교집합."""
    return detect_categories(user_text) & describe_categories(case_text)
